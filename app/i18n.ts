const englishTypeReplacements: Array<[RegExp, string]> = [
  [/非 IDR 切片/g, "Non-IDR Slice"],
  [/切片数据 ([ABC])/g, "Slice Data $1"],
  [/关键帧/g, "Key Frame"],
  [/切片/g, "Slice"],
  [/VPS 视频参数集/g, "VPS Video Parameter Set"],
  [/SPS 序列参数集/g, "SPS Sequence Parameter Set"],
  [/PPS 图像参数集/g, "PPS Picture Parameter Set"],
  [/AUD 访问单元分隔符/g, "AUD Access Unit Delimiter"],
  [/序列结束/g, "End of Sequence"],
  [/码流结束/g, "End of Bitstream"],
  [/填充数据/g, "Filler Data"],
  [/前缀 SEI/g, "Prefix SEI"],
  [/后缀 SEI/g, "Suffix SEI"],
  [/前缀 APS/g, "Prefix APS"],
  [/后缀 APS/g, "Suffix APS"],
  [/操作点信息/g, "Operating Point Information"],
  [/解码能力信息/g, "Decoder Capability Information"],
  [/图像头/g, "Picture Header"],
  [/GDR 图像/g, "GDR Picture"],
  [/保留 IRAP/g, "Reserved IRAP"],
  [/保留类型/g, "Reserved Type"],
  [/保留 NAL/g, "Reserved NAL"],
];

export function localizeTypeName(name: string, locale: Locale) {
  if (locale === "zh-CN") return name;
  return englishTypeReplacements.reduce((value, [pattern, replacement]) => value.replace(pattern, replacement), name);
}

export function localizeBlockName(name: string, locale: Locale) {
  return locale === "en" && name === "编码树单元" ? "CTU" : name;
}

export function localizeParameterSetName(name: string, locale: Locale) {
  if (locale === "zh-CN") return name;
  if (name === "HEVC SPS 参数") return "HEVC SPS parameters";
  if (name === "VVC 参数集") return "VVC parameter sets";
  return name;
}
